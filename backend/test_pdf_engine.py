def run_tests():
    print("=== Running Step 3 ATS-Proof PDF Engine Acceptance Tests ===\n")
    vault, tailored = build_test_fixtures()

    # 1. Direct unit test of generate_ats_pdf and verify_ats_pdf_extractable
    print("[TEST 1] Direct Generation & Extraction Verification:")
    pdf_bytes = generate_ats_pdf(vault=vault, tailored=tailored)
    assert pdf_bytes.startswith(b"%PDF-"), "Generated bytes must have valid PDF header"
    print(f"Generated PDF size: {len(pdf_bytes)} bytes.")

    verification = verify_ats_pdf_extractable(pdf_bytes=pdf_bytes, vault=vault, tailored=tailored)
    assert verification["passed"] is True
    assert verification["page_count"] >= 1
    assert verification["extracted_char_count"] > 100
    print(f"Verification passed! Pages: {verification['page_count']} | Extracted chars: {verification['extracted_char_count']}\n")

    # 2. Test POST /api/v1/pdf/generate endpoint
    print("[TEST 2] POST /api/v1/pdf/generate Endpoint Test:")
    payload = {
        "vault": vault.model_dump(mode="json"),
        "tailored_resume": tailored.model_dump(mode="json"),
    }
    resp = client.post("/api/v1/pdf/generate", json=payload)
    print(f"Status Code: {resp.status_code}")
    assert resp.status_code == 200, f"Expected 200, got {resp.status_code}: {resp.text}"
    assert resp.headers["content-type"] == "application/pdf"
    assert resp.headers["X-ATS-PDF-Verified"] == "true"
    assert int(resp.headers["X-ATS-PDF-Pages"]) >= 1

    resp_bytes = resp.content
    assert resp_bytes.startswith(b"%PDF-")

    # 3. Independent pypdf parse of HTTP response bytes
    print("[TEST 3] Independent pypdf Validation of Response Bytes:")
    reader = PdfReader(io.BytesIO(resp_bytes))
    extracted_text = "".join(page.extract_text() or "" for page in reader.pages)
    text_lower = extracted_text.lower()

    # Verify candidate name, email, sections, and project names
    assert vault.basics.full_name.lower() in text_lower, "Full name must appear in text"
    assert vault.basics.email.lower() in text_lower, "Email must appear in text"
    assert "chronoqueue" in text_lower, "Project ChronoQueue must appear in text"
    assert "indicdoc" in text_lower, "Project IndicDoc must appear in text"
    assert "experience" in text_lower, "Experience section must appear in text"
    assert "education" in text_lower, "Education section must appear in text"
    assert "skills" in text_lower, "Skills section must appear in text"

    # Strictly verify that raw HTML/XML markup tags never leak into extracted text
    for tag in ["<i>", "</i>", "<b>", "</b>", "<a", "</a>", "&lt;", "&gt;"]:
        assert tag not in text_lower, f"Raw markup tag/entity '{tag}' must NOT appear in extracted PDF text"

    print("--- EXTRACTED TEXT PREVIEW FROM PYPDF ---")
    print(extracted_text[:400].strip())
    print("-----------------------------------------\n")

    # 4. Save sample PDF to backend/data/sample_ats_resume.pdf for inspection
    data_dir = Path(__file__).resolve().parent / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    sample_pdf_path = data_dir / "sample_ats_resume.pdf"
    with open(sample_pdf_path, "wb") as f:
        f.write(resp_bytes)
    assert sample_pdf_path.exists(), "Sample PDF file must be written to disk"
    print(f"[SAMPLE OUTPUT] Saved sample PDF to: {sample_pdf_path}\n")

    # 5. Full Pipeline Regression Checks
    print("[TEST 5] Full System Regression Checks:")
    health_resp = client.get("/health")
    assert health_resp.status_code == 200

    val_resp = client.post("/api/v1/vault/validate", json=vault.model_dump(mode="json"))
    assert val_resp.status_code == 200

    # Test /pipeline/run with mocked pass critique
    pass_critique = ATSCritique(
        score=95,
        passed=True,
        matched_keywords=["Go", "Python", "PostgreSQL", "Redis"],
        missing_must_have_skills=[],
        missing_ats_keywords=[],
        actionable_feedback=[],
        hallucination_flags=[],
    )
    decoded_jd = DecodedJD(
        role_title="Backend Intern",
        role_level="intern",
        company_vibe="startup",
        detected_portal="internshala",
        must_have_skills=["Go", "Python"],
        nice_to_have_skills=[],
        ats_keywords=["Microservices"],
        key_responsibilities=[],
        eligibility_constraints=EligibilityConstraints(),
    )
    jd_decoder.default_llm_override = decoded_jd
    resume_architect.default_llm_override = tailored
    ats_critic.default_llm_override = pass_critique

    try:
        pipeline_resp = client.post(
            "/api/v1/pipeline/run",
            json={
                "vault": vault.model_dump(mode="json"),
                "raw_jd_text": "Hiring a Go backend developer intern with python microservices experience.",
            },
        )
        assert pipeline_resp.status_code == 200
        assert pipeline_resp.json()["status"] == "passed"
        print("Pipeline regression check passed successfully.\n")
    finally:
        jd_decoder.default_llm_override = None
        resume_architect.default_llm_override = None
        ats_critic.default_llm_override = None

    print("=== ALL STEP 3 PDF ENGINE TESTS PASSED SUCCESSFULLY ===")


if __name__ == "__main__":
    run_tests()
